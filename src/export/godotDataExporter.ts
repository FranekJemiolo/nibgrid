import { strToU8 } from 'fflate';
import {
  sanitizeDataId,
  type EnemyStatBlock,
  type GameDataRegistry,
  type LootTable,
  type WeaponItem,
} from '../data/gameDataSchemas';
import type { VirtualSyncFile } from './godotPrefabAssembler';

export type GameDataResourceKind = 'weapon' | 'enemy' | 'loot_table';

function escapeGodotString(value: string): string {
  return value
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n');
}

function formatGodotFloat(value: number, fallback = 0): string {
  const safe = Number.isFinite(value) ? value : fallback;
  const rounded = Number(safe.toFixed(4));
  const clean = Object.is(rounded, -0) ? 0 : rounded;
  return Number.isInteger(clean) ? `${clean}.0` : String(clean);
}

function formatGodotInt(value: number, fallback = 0): number {
  const safe = Number.isFinite(value) ? Math.round(value) : fallback;
  return Object.is(safe, -0) ? 0 : safe;
}

/**
 * Emits typed Godot 4.3+ `Resource` schema classes saved to `res://data/schemas/`.
 */
export function exportResourceSchemaGd(kind: GameDataResourceKind): string {
  if (kind === 'weapon') {
    return [
      'extends Resource',
      'class_name WeaponItemData',
      '',
      '## Auto-generated by Nibgrid Milestone 46',
      '@export var id: String = ""',
      '@export var display_name: String = ""',
      '@export var base_damage: float = 10.0',
      '@export var attacks_per_second: float = 1.5',
      '@export var crit_chance: float = 0.1',
      '@export var crit_multiplier: float = 2.0',
      '@export var gold_value: int = 0',
      '@export var icon_asset_id: String = ""',
      '',
    ].join('\n');
  }

  if (kind === 'enemy') {
    return [
      'extends Resource',
      'class_name EnemyStatData',
      '',
      '## Auto-generated by Nibgrid Milestone 46',
      '@export var id: String = ""',
      '@export var display_name: String = ""',
      '@export var entity_id: String = ""',
      '@export var max_hp: float = 50.0',
      '@export var armor: float = 0.0',
      '@export var attack_damage: float = 5.0',
      '@export var attacks_per_second: float = 1.0',
      '@export var xp_reward: float = 10.0',
      '@export var loot_table_id: String = ""',
      '',
    ].join('\n');
  }

  return [
    'extends Resource',
    'class_name LootTableData',
    '',
    '## Auto-generated by Nibgrid Milestone 46',
    '@export var id: String = ""',
    '@export var rolls: int = 1',
    '@export var entries_json: String = "[]"',
    '',
  ].join('\n');
}

/**
 * Serializes a single `WeaponItem` into a Godot 4 `format=3` `.tres` resource file.
 */
export function exportWeaponTres(weapon: WeaponItem): string {
  const safeId = sanitizeDataId(weapon.id, 'weapon');
  const lines = [
    '[gd_resource type="Resource" script_class="WeaponItemData" load_steps=2 format=3]',
    '',
    '[ext_resource type="Script" path="res://data/schemas/WeaponItemData.gd" id="1_script"]',
    '',
    '[resource]',
    'script = ExtResource("1_script")',
    `id = "${escapeGodotString(safeId)}"`,
    `display_name = "${escapeGodotString(weapon.displayName)}"`,
    `base_damage = ${formatGodotFloat(weapon.baseDamage, 0)}`,
    `attacks_per_second = ${formatGodotFloat(weapon.attacksPerSecond, 1)}`,
    `crit_chance = ${formatGodotFloat(weapon.critChance, 0)}`,
    `crit_multiplier = ${formatGodotFloat(weapon.critMultiplier, 1)}`,
    `gold_value = ${formatGodotInt(weapon.goldValue, 0)}`,
  ];
  if (weapon.iconAssetId) {
    lines.push(`icon_asset_id = "${escapeGodotString(weapon.iconAssetId)}"`);
  }
  lines.push('');
  return lines.join('\n');
}

/**
 * Serializes a single `EnemyStatBlock` into a Godot 4 `format=3` `.tres` resource file.
 */
export function exportEnemyTres(enemy: EnemyStatBlock): string {
  const safeId = sanitizeDataId(enemy.id, 'enemy');
  const lines = [
    '[gd_resource type="Resource" script_class="EnemyStatData" load_steps=2 format=3]',
    '',
    '[ext_resource type="Script" path="res://data/schemas/EnemyStatData.gd" id="1_script"]',
    '',
    '[resource]',
    'script = ExtResource("1_script")',
    `id = "${escapeGodotString(safeId)}"`,
    `display_name = "${escapeGodotString(enemy.displayName || safeId)}"`,
    `max_hp = ${formatGodotFloat(enemy.maxHp, 50)}`,
    `armor = ${formatGodotFloat(enemy.armor, 0)}`,
    `attack_damage = ${formatGodotFloat(enemy.attackDamage, 0)}`,
    `attacks_per_second = ${formatGodotFloat(enemy.attacksPerSecond, 1)}`,
    `xp_reward = ${formatGodotFloat(enemy.xpReward, 0)}`,
  ];
  if (enemy.entityId) {
    lines.push(`entity_id = "${escapeGodotString(enemy.entityId)}"`);
  }
  if (enemy.lootTableId) {
    lines.push(`loot_table_id = "${escapeGodotString(enemy.lootTableId)}"`);
  }
  lines.push('');
  return lines.join('\n');
}

/**
 * Serializes a single `LootTable` into a Godot 4 `format=3` `.tres` resource file.
 */
export function exportLootTableTres(lootTable: LootTable): string {
  const safeId = sanitizeDataId(lootTable.id, 'loot_table');
  const entriesJson = escapeGodotString(JSON.stringify(lootTable.entries));
  return [
    '[gd_resource type="Resource" script_class="LootTableData" load_steps=2 format=3]',
    '',
    '[ext_resource type="Script" path="res://data/schemas/LootTableData.gd" id="1_script"]',
    '',
    '[resource]',
    'script = ExtResource("1_script")',
    `id = "${escapeGodotString(safeId)}"`,
    `rolls = ${Math.max(1, formatGodotInt(lootTable.rolls, 1))}`,
    `entries_json = "${entriesJson}"`,
    '',
  ].join('\n');
}

/**
 * Emits all virtual `res://data/` files for M25 SHA-256 sync (`schemas/*.gd`, `items/*.tres`,
 * `enemies/*.tres`, `loot/*.tres`, and `progression_curves.json`).
 */
export function assembleGodotGameDataFiles(registry: GameDataRegistry): readonly VirtualSyncFile[] {
  const files: VirtualSyncFile[] = [
    {
      relativePath: 'data/schemas/WeaponItemData.gd',
      content: strToU8(exportResourceSchemaGd('weapon')),
    },
    {
      relativePath: 'data/schemas/EnemyStatData.gd',
      content: strToU8(exportResourceSchemaGd('enemy')),
    },
    {
      relativePath: 'data/schemas/LootTableData.gd',
      content: strToU8(exportResourceSchemaGd('loot_table')),
    },
    {
      relativePath: 'data/progression_curves.json',
      content: strToU8(`${JSON.stringify(registry.progressionCurves, null, 2)}\n`),
    },
  ];

  for (const weapon of registry.items) {
    const safeId = sanitizeDataId(weapon.id, 'weapon');
    files.push({
      relativePath: `data/items/${safeId}.tres`,
      content: strToU8(exportWeaponTres(weapon)),
    });
  }

  for (const enemy of registry.enemies) {
    const safeId = sanitizeDataId(enemy.id, 'enemy');
    files.push({
      relativePath: `data/enemies/${safeId}.tres`,
      content: strToU8(exportEnemyTres(enemy)),
    });
  }

  for (const table of registry.lootTables) {
    const safeId = sanitizeDataId(table.id, 'loot_table');
    files.push({
      relativePath: `data/loot/${safeId}.tres`,
      content: strToU8(exportLootTableTres(table)),
    });
  }

  return files;
}

export interface PlaytestCombatPatch {
  readonly attackDamage: number;
  readonly dummyMaxHp: number;
  readonly attackCooldownMs: number;
  readonly enemyArmor: number;
  readonly enemyAttackDamage: number;
}

/**
 * Bridges a tuned `WeaponItem` × `EnemyStatBlock` pair directly into M36 Playtest parameters.
 */
export function toPlaytestCombatPatch(
  weapon: WeaponItem,
  enemy: EnemyStatBlock,
): PlaytestCombatPatch {
  const attackDamage = Math.max(1, Math.min(999, Math.round(weapon.baseDamage)));
  const dummyMaxHp = Math.max(1, Math.round(enemy.maxHp));
  const attackCooldownMs = Math.max(
    80,
    Math.min(3000, Math.round(1000 / Math.max(0.2, weapon.attacksPerSecond))),
  );
  return {
    attackDamage,
    dummyMaxHp,
    attackCooldownMs,
    enemyArmor: Math.max(0, enemy.armor),
    enemyAttackDamage: Math.max(0, enemy.attackDamage),
  };
}
