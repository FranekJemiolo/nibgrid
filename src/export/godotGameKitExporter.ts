/**
 * Generates `scripts/GameShell.gd` handling Title Screen Start button, Pause toggle,
 * HP Bar updates, Minimap toggle, and M47 Dialogue Box signal wiring.
 */
export function exportGameShellGd(
  templateId: GameKitTemplateId,
  projectName = 'Nibgrid Game',
): string {
  return [
    'extends Node2D',
    'class_name GameShell',
    '',
    `## Auto-generated by Nibgrid Milestone 50 (${templateId} — ${escapeGodotString(projectName)})`,
    '@onready var title_screen: Control = $UiLayer/TitleScreen',
    '@onready var hud_root: Control = $UiLayer/HudRoot',
    '@onready var pause_menu: Control = $UiLayer/PauseMenu',
    '@onready var hp_bar: ProgressBar = $UiLayer/HudRoot/HpBar',
    '@onready var dialogue_panel: PanelContainer = $UiLayer/HudRoot/DialogueBox',
    '@onready var dialogue_label: Label = $UiLayer/HudRoot/DialogueBox/DialogueText',
    '@onready var level_root: Node2D = $LevelRoot',
    '',
    'var _game_started: bool = false',
    '',
    'func _ready() -> void:',
    '\tprocess_mode = Node.PROCESS_MODE_ALWAYS',
    '\ttitle_screen.visible = true',
    '\thud_root.visible = false',
    '\tpause_menu.visible = false',
    '\tdialogue_panel.visible = false',
    '\tif level_root != null:',
    '\t\tlevel_root.process_mode = Node.PROCESS_MODE_PAUSABLE',
    '\tvar start_btn := title_screen.get_node_or_null("StartButton") as Button',
    '\tif start_btn != null:',
    '\t\tstart_btn.pressed.connect(_on_start_pressed)',
    '\tvar resume_btn := pause_menu.get_node_or_null("ResumeButton") as Button',
    '\tif resume_btn != null:',
    '\t\tresume_btn.pressed.connect(_toggle_pause)',
    '',
    'func _unhandled_input(event: InputEvent) -> void:',
    '\tif _game_started and event.is_action_pressed("pause"):',
    '\t\t_toggle_pause()',
    '',
    'func _on_start_pressed() -> void:',
    '\t_game_started = true',
    '\ttitle_screen.visible = false',
    '\thud_root.visible = true',
    '\tget_tree().paused = false',
    '',
    'func _toggle_pause() -> void:',
    '\tvar next_paused := not get_tree().paused',
    '\tget_tree().paused = next_paused',
    '\tpause_menu.visible = next_paused',
    '',
    'func set_hp(current_hp: float, max_hp: float) -> void:',
    '\tif hp_bar != null:',
    '\t\thp_bar.max_value = max(1.0, max_hp)',
    '\t\thp_bar.value = clampf(current_hp, 0.0, hp_bar.max_value)',
    '',
    'func show_dialogue(text: String) -> void:',
    '\tif dialogue_panel != null and dialogue_label != null:',
    '\t\tdialogue_label.text = text',
    '\t\tdialogue_panel.visible = not text.is_empty()',
    '',
  ].join('\n');
}

/**
 * Emits a playable `res://main.tscn` wiring Title Screen (M33 Theme + M24 Font),
 * In-Game HUD (HP Bar + M45 Minimap + M47 Dialogue Box), Pause Menu, optional Room level,
 * and `GameShell.gd`.
 */
export function exportPlayableMainTscn(opts: {
  readonly projectName: string;
  readonly templateId: GameKitTemplateId;
  readonly levelResPath?: string;
  readonly themeResPath?: string;
  readonly fontResPath?: string;
  readonly minimapResPath?: string;
}): string {
  const safeName = escapeGodotString(opts.projectName.trim() || 'Nibgrid Game');
  const extResources: string[] = [
    '[ext_resource type="Script" path="res://scripts/GameShell.gd" id="1_shell"]',
  ];

  let nextIdx = 2;
  let levelExtId: string | null = null;
  if (opts.levelResPath?.trim()) {
    levelExtId = `${nextIdx++}_lvl`;
    extResources.push(
      `[ext_resource type="PackedScene" path="${escapeGodotString(opts.levelResPath.trim())}" id="${levelExtId}"]`,
    );
  }
  let themeExtId: string | null = null;
  if (opts.themeResPath?.trim()) {
    themeExtId = `${nextIdx++}_thm`;
    extResources.push(
      `[ext_resource type="Theme" path="${escapeGodotString(opts.themeResPath.trim())}" id="${themeExtId}"]`,
    );
  }
  let minimapExtId: string | null = null;
  if (opts.minimapResPath?.trim()) {
    minimapExtId = `${nextIdx++}_map`;
    extResources.push(
      `[ext_resource type="Texture2D" path="${escapeGodotString(opts.minimapResPath.trim())}" id="${minimapExtId}"]`,
    );
  }

  const loadSteps = extResources.length + 1;
  const themeLine = themeExtId ? `theme = ExtResource("${themeExtId}")` : null;

  return [
    `[gd_scene load_steps=${loadSteps} format=3]`,
    '',
    ...extResources,
    '',
    '[node name="Main" type="Node2D"]',
    'script = ExtResource("1_shell")',
    '',
    '[node name="LevelRoot" type="Node2D" parent="."]',
    ...(levelExtId
      ? ['', `[node name="ActiveLevel" parent="LevelRoot" instance=ExtResource("${levelExtId}")]`]
      : []),
    '',
    '[node name="UiLayer" type="CanvasLayer" parent="."]',
    'process_mode = 3',
    '',
    '[node name="TitleScreen" type="Control" parent="UiLayer"]',
    'layout_mode = 3',
    'anchors_preset = 15',
    'anchor_right = 1.0',
    'anchor_bottom = 1.0',
    ...(themeLine ? [themeLine] : []),
    '',
    '[node name="TitleLabel" type="Label" parent="UiLayer/TitleScreen"]',
    'offset_left = 24.0',
    'offset_top = 24.0',
    'offset_right = 296.0',
    'offset_bottom = 52.0',
    `text = "${safeName}"`,
    '',
    '[node name="StartButton" type="Button" parent="UiLayer/TitleScreen"]',
    'offset_left = 24.0',
    'offset_top = 68.0',
    'offset_right = 160.0',
    'offset_bottom = 96.0',
    'text = "Start Game"',
    '',
    '[node name="HudRoot" type="Control" parent="UiLayer"]',
    'visible = false',
    'layout_mode = 3',
    'anchors_preset = 15',
    'anchor_right = 1.0',
    'anchor_bottom = 1.0',
    ...(themeLine ? [themeLine] : []),
    '',
    '[node name="HpBar" type="ProgressBar" parent="UiLayer/HudRoot"]',
    'offset_left = 12.0',
    'offset_top = 12.0',
    'offset_right = 132.0',
    'offset_bottom = 28.0',
    'value = 100.0',
    '',
    '[node name="MinimapPanel" type="TextureRect" parent="UiLayer/HudRoot"]',
    'offset_left = 248.0',
    'offset_top = 10.0',
    'offset_right = 310.0',
    'offset_bottom = 56.0',
    ...(minimapExtId ? [`texture = ExtResource("${minimapExtId}")`] : []),
    'stretch_mode = 5',
    '',
    '[node name="DialogueBox" type="PanelContainer" parent="UiLayer/HudRoot"]',
    'visible = false',
    'offset_left = 20.0',
    'offset_top = 120.0',
    'offset_right = 300.0',
    'offset_bottom = 172.0',
    '',
    '[node name="DialogueText" type="Label" parent="UiLayer/HudRoot/DialogueBox"]',
    'autowrap_mode = 2',
    'text = ""',
    '',
    '[node name="PauseMenu" type="Control" parent="UiLayer"]',
    'visible = false',
    'layout_mode = 3',
    'anchors_preset = 15',
    'anchor_right = 1.0',
    'anchor_bottom = 1.0',
    ...(themeLine ? [themeLine] : []),
    '',
    '[node name="ResumeButton" type="Button" parent="UiLayer/PauseMenu"]',
    'offset_left = 96.0',
    'offset_top = 74.0',
    'offset_right = 224.0',
    'offset_bottom = 102.0',
    'text = "Resume"',
    '',
  ].join('\n');
}
