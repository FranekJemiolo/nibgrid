export type GameKitTemplateId = 'side-platformer' | 'top-down-action' | 'cozy-rpg';

export interface GameKitTemplateMeta {
  readonly id: GameKitTemplateId;
  readonly label: string;
  readonly description: string;
  readonly defaultGravity: number;
  readonly topDownMovement: boolean;
}

export const GAMEKIT_TEMPLATES: readonly GameKitTemplateMeta[] = [
  {
    id: 'side-platformer',
    label: 'Side-Platformer GameKit',
    description:
      'Gravity, coyote-time jump, horizontal run, melee hitbox tracks & 2D platform layers.',
    defaultGravity: 980,
    topDownMovement: false,
  },
  {
    id: 'top-down-action',
    label: 'Top-Down Action GameKit',
    description: '8-way movement, zero-gravity arena physics, dash cooldown & directional combat.',
    defaultGravity: 0,
    topDownMovement: true,
  },
  {
    id: 'cozy-rpg',
    label: 'Cozy RPG GameKit',
    description:
      'Smooth top-down town navigation, NPC interact prompt, dialogue HUD & item pickups.',
    defaultGravity: 0,
    topDownMovement: true,
  },
];

function escapeGodotString(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

function makeInputKeyEvent(physicalKeycode: number): string {
  return `Object(InputEventKey,"resource_local_to_scene":false,"resource_name":"","device":-1,"window_id":0,"alt_pressed":false,"shift_pressed":false,"ctrl_pressed":false,"meta_pressed":false,"pressed":false,"keycode":0,"physical_keycode":${physicalKeycode},"key_label":0,"unicode":0,"location":0,"echo":false,"script":null)`;
}

function makeJoypadButtonEvent(buttonIndex: number): string {
  return `Object(InputEventJoypadButton,"resource_local_to_scene":false,"resource_name":"","device":-1,"button_index":${buttonIndex},"pressure":0.0,"pressed":true,"script":null)`;
}

/**
 * Generates a turnkey Godot 4.3+ `project.godot` (`config_version=5`) with pre-wired InputMap
 * (`move_left`, `move_right`, `move_up`, `move_down`, `jump`, `attack`, `interact`, `pause`),
 * named 2D physics layers (`1: World` .. `7: Interactable`), pixel-perfect scaling, autoloads,
 * and `addons/nibgrid_sync/plugin.cfg` enabled.
 */
export function exportProjectGodot(opts: {
  readonly projectName: string;
  readonly templateId: GameKitTemplateId;
  readonly viewportWidth?: number;
  readonly viewportHeight?: number;
  readonly isPixelArt?: boolean;
  readonly includeWorldAutoload?: boolean;
  readonly includeDialogueAutoload?: boolean;
  readonly includeSaveAutoload?: boolean;
}): string {
  const name = escapeGodotString(opts.projectName.trim() || 'NibgridGame');
  const vw = Math.max(160, Math.round(opts.viewportWidth ?? 320));
  const vh = Math.max(120, Math.round(opts.viewportHeight ?? 180));
  const isPixelArt = opts.isPixelArt ?? true;
  const tpl = GAMEKIT_TEMPLATES.find((t) => t.id === opts.templateId) ?? GAMEKIT_TEMPLATES[0]!;

  const inputActions: readonly (readonly [string, readonly string[]])[] = [
    ['move_left', [makeInputKeyEvent(65), makeInputKeyEvent(4194319)]],
    ['move_right', [makeInputKeyEvent(68), makeInputKeyEvent(4194321)]],
    ['move_up', [makeInputKeyEvent(87), makeInputKeyEvent(4194320)]],
    ['move_down', [makeInputKeyEvent(83), makeInputKeyEvent(4194322)]],
    ['jump', [makeInputKeyEvent(32), makeJoypadButtonEvent(0)]],
    ['attack', [makeInputKeyEvent(90), makeJoypadButtonEvent(2)]],
    ['interact', [makeInputKeyEvent(69), makeJoypadButtonEvent(3)]],
    ['pause', [makeInputKeyEvent(4194305), makeJoypadButtonEvent(6)]],
  ];

  const autoloadLines: string[] = [];
  if (opts.includeWorldAutoload) {
    autoloadLines.push('WorldTransitionManager="*res://world/WorldTransitionManager.gd"');
  }
  if (opts.includeDialogueAutoload) {
    autoloadLines.push('DialogueRunner="*res://narrative/DialogueRunner.gd"');
  }
  if (opts.includeSaveAutoload) {
    autoloadLines.push('SaveManager="*res://scripts/runtime/SaveManager.gd"');
  }

  return [
    '; Engine configuration file.',
    '; Auto-generated by Nibgrid Milestone 50 (Turnkey GameKit)',
    'config_version=5',
    '',
    '[application]',
    `config/name="${name}"`,
    `config/description="Built with Nibgrid (${tpl.label})"`,
    'run/main_scene="res://main.tscn"',
    'config/features=PackedStringArray("4.3", "Forward Plus")',
    'audio/buses/default_bus_layout="res://default_bus_layout.tres"',
    '',
    ...(autoloadLines.length > 0 ? ['[autoload]', ...autoloadLines, ''] : []),
    '[display]',
    `window/size/viewport_width=${vw}`,
    `window/size/viewport_height=${vh}`,
    'window/size/window_width_override=1280',
    'window/size/window_height_override=720',
    ...(isPixelArt
      ? ['window/stretch/mode="canvas_items"', 'window/stretch/scale_mode="integer"']
      : ['window/stretch/mode="canvas_items"']),
    '',
    '[editor_plugins]',
    'enabled=PackedStringArray("res://addons/nibgrid_sync/plugin.cfg")',
    '',
    '[input]',
    ...inputActions.map(
      ([action, events]) => `${action}={\n"deadzone": 0.2,\n"events": [${events.join(', ')}]\n}`,
    ),
    '',
    '[layer_names]',
    '2d_physics/layer_1="World"',
    '2d_physics/layer_2="Player"',
    '2d_physics/layer_3="Enemy"',
    '2d_physics/layer_4="Hitbox"',
    '2d_physics/layer_5="Hurtbox"',
    '2d_physics/layer_6="Portal"',
    '2d_physics/layer_7="Interactable"',
    '',
    '[physics]',
    `2d/default_gravity=${tpl.defaultGravity}.0`,
    '',
    '[rendering]',
    ...(isPixelArt ? ['textures/canvas_textures/default_texture_filter=0'] : []),
    '2d/snap/snap_2d_transforms_to_pixel=' + (isPixelArt ? 'true' : 'false'),
    '2d/snap/snap_2d_vertices_to_pixel=' + (isPixelArt ? 'true' : 'false'),
    '',
  ].join('\n');
}

