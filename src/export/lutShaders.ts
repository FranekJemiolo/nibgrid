/**
 * Generates Godot 4 (`canvas_item`) palette-swap shader enforcing `filter_nearest`,
 * texel-center `(palette_idx + 0.5)` UV lookup, and built-in damage flash uniforms.
 */
export function generateGodotPaletteSwapShader(
  slug: string,
  paletteSize: number,
  variantCount: number,
): string {
  const cleanSlug = slug.replace(/\\/g, '/');
  return [
    `// Nibgrid Indexed Palette-Swap Shader (${cleanSlug}: ${paletteSize} colors x ${variantCount} variants)`,
    `// Import ${cleanSlug}_idx.png with Texture Filter = Nearest (and linear/non-sRGB in HDR2D).`,
    'shader_type canvas_item;',
    '',
    'uniform sampler2D lut_tex : source_color, filter_nearest, repeat_disable;',
    'uniform int variant_index = 0;',
    'uniform float flash_amount : hint_range(0.0, 1.0) = 0.0;',
    'uniform vec3 flash_color : source_color = vec3(1.0, 1.0, 1.0);',
    '',
    'void fragment() {',
    '    vec4 idx_sample = texture(TEXTURE, UV);',
    '    if (idx_sample.a < 0.01) {',
    '        discard;',
    '    }',
    '',
    '    ivec2 lut_size = textureSize(lut_tex, 0);',
    '    float palette_idx = floor(idx_sample.r * 255.0 + 0.5);',
    '    float row = clamp(float(variant_index), 0.0, float(max(lut_size.y - 1, 0)));',
    '',
    '    vec2 lut_uv = vec2(',
    '        (palette_idx + 0.5) / float(max(lut_size.x, 1)),',
    '        (row + 0.5) / float(max(lut_size.y, 1))',
    '    );',
    '',
    '    vec3 swapped = texture(lut_tex, lut_uv).rgb;',
    '    vec3 final_rgb = mix(swapped, flash_color, flash_amount);',
    '    COLOR = vec4(final_rgb, idx_sample.a) * modulate;',
    '}',
    '',
  ].join('\n');
}

/**
 * Generates PixiJS v8 Filter factory enforcing `scaleMode = 'nearest'` on the LUT texture
 * and un-premultiplying index channels prior to `(paletteIdx + 0.5) / uPaletteSize` lookup.
 */
export function generatePixiPaletteSwapFilterTs(
  slug: string,
  paletteSize: number,
  variantCount: number,
): string {
  const cleanSlug = slug.replace(/\\/g, '/');
  return [
    `// Nibgrid PixiJS v8 Palette-Swap Filter (${cleanSlug}: ${paletteSize} colors x ${variantCount} variants)`,
    "import { Filter, GlProgram, Texture } from 'pixi.js';",
    '',
    'const vertex = /* glsl */ `',
    'in vec2 aPosition;',
    'out vec2 vTextureCoord;',
    '',
    'uniform vec4 uInputSize;',
    'uniform vec4 uOutputFrame;',
    'uniform vec4 uOutputTexture;',
    '',
    'vec4 filterVertexPosition(void) {',
    '  vec2 position = aPosition * uOutputFrame.zw + uOutputFrame.xy;',
    '  position.x = position.x * (2.0 / uOutputTexture.x) - 1.0;',
    '  position.y = position.y * (2.0 * uOutputTexture.z / uOutputTexture.y) - uOutputTexture.z;',
    '  return vec4(position, 0.0, 1.0);',
    '}',
    '',
    'vec2 filterTextureCoord(void) {',
    '  return aPosition * (uOutputFrame.zw * uInputSize.zw);',
    '}',
    '',
    'void main(void) {',
    '  gl_Position = filterVertexPosition();',
    '  vTextureCoord = filterTextureCoord();',
    '}',
    '`;',
    '',
    'const fragment = /* glsl */ `',
    'precision highp float;',
    'in vec2 vTextureCoord;',
    'out vec4 finalColor;',
    '',
    'uniform sampler2D uTexture;',
    'uniform sampler2D uLutTexture;',
    'uniform float uPaletteSize;',
    'uniform float uVariantCount;',
    'uniform float uVariantRow;',
    '',
    'void main(void) {',
    '  vec4 idxSample = texture(uTexture, vTextureCoord);',
    '  if (idxSample.a < 0.01) {',
    '    finalColor = vec4(0.0);',
    '    return;',
    '  }',
    '  float rawR = idxSample.r / max(idxSample.a, 0.0001);',
    '  float paletteIdx = floor(rawR * 255.0 + 0.5);',
    '  vec2 lutUv = vec2(',
    '    (paletteIdx + 0.5) / max(uPaletteSize, 1.0),',
    '    (clamp(uVariantRow, 0.0, max(uVariantCount - 1.0, 0.0)) + 0.5) / max(uVariantCount, 1.0)',
    '  );',
    '  vec3 swapped = texture(uLutTexture, lutUv).rgb;',
    '  finalColor = vec4(swapped * idxSample.a, idxSample.a);',
    '}',
    '`;',
    '',
    'export function createPaletteSwapFilter(lutTexture: Texture, variantRow = 0): Filter {',
    "  lutTexture.source.scaleMode = 'nearest';",
    '  return new Filter({',
    '    glProgram: new GlProgram({ vertex, fragment }),',
    '    resources: {',
    '      uLutTexture: lutTexture.source,',
    '      swapUniforms: {',
    '        uPaletteSize: { value: lutTexture.width, type: "f32" },',
    '        uVariantCount: { value: lutTexture.height, type: "f32" },',
    '        uVariantRow: { value: variantRow, type: "f32" },',
    '      },',
    '    },',
    '  });',
    '}',
    '',
  ].join('\n');
}

