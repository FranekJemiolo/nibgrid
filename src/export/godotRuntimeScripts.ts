import { GAMEKIT_TEMPLATES, type GameKitTemplateId } from './godotGameKitExporter';

export interface GeneratedRuntimeScriptFile {
  readonly relativePath: string;
  readonly content: string;
}

/**
 * Generates turnkey, strictly typed Godot 4.3+ runtime GDScript controllers
 * (`PlayerController.gd`, `EnemyAiController.gd`, `NpcController.gd`, `SaveManager.gd`)
 * wired directly into composable `.tscn` prefabs and `project.godot` autoloads.
 */
export function exportGameKitRuntimeScripts(
  templateId: GameKitTemplateId,
): readonly GeneratedRuntimeScriptFile[] {
  const tpl = GAMEKIT_TEMPLATES.find((t) => t.id === templateId) ?? GAMEKIT_TEMPLATES[0]!;
  const isTopDown = tpl.topDownMovement ? 'true' : 'false';
  const defaultGravity = `${tpl.defaultGravity}.0`;

  const playerGd = [
    'extends CharacterBody2D',
    'class_name NibgridPlayerController',
    '',
    '## Auto-generated by Nibgrid Milestone 56 (Playable F5 Player Controller)',
    '@export var move_speed: float = 140.0',
    '@export var jump_velocity: float = -310.0',
    `@export var gravity_px: float = ${defaultGravity}`,
    '@export var attack_damage: float = 20.0',
    '@export var attack_cooldown_sec: float = 0.35',
    '@export var coyote_time_sec: float = 0.12',
    `@export var top_down_movement: bool = ${isTopDown}`,
    '',
    '@onready var _sprite: Sprite2D = get_node_or_null("Sprite2D") as Sprite2D',
    '@onready var _anim_player: AnimationPlayer = get_node_or_null("AnimationPlayer") as AnimationPlayer',
    '@onready var _health: Node = get_node_or_null("HealthComponent")',
    '@onready var _hurtbox: Area2D = get_node_or_null("HurtboxComponent") as Area2D',
    '@onready var _hitbox: Area2D = get_node_or_null("HitboxComponent") as Area2D',
    '@onready var _fsm: Node = get_node_or_null("StateMachine")',
    '',
    'var _coyote_timer: float = 0.0',
    'var _attack_timer: float = 0.0',
    'var _invuln_timer: float = 0.0',
    '',
    'func _ready() -> void:',
    '\tadd_to_group(&"player")',
    '\tif get_node_or_null("Camera2D") == null:',
    '\t\tvar cam := Camera2D.new()',
    '\t\tcam.name = "Camera2D"',
    '\t\tcam.position_smoothing_enabled = true',
    '\t\tadd_child(cam)',
    '\tif _hurtbox != null and not _hurtbox.area_entered.is_connected(_on_hurtbox_area_entered):',
    '\t\t_hurtbox.area_entered.connect(_on_hurtbox_area_entered)',
    '\tif _hitbox != null and not _hitbox.area_entered.is_connected(_on_hitbox_area_entered):',
    '\t\t_hitbox.area_entered.connect(_on_hitbox_area_entered)',
    '',
    'func _physics_process(delta: float) -> void:',
    '\t_attack_timer = maxf(0.0, _attack_timer - delta)',
    '\t_invuln_timer = maxf(0.0, _invuln_timer - delta)',
    '',
    '\tif top_down_movement:',
    '\t\tvar input_vec := Input.get_vector("move_left", "move_right", "move_up", "move_down")',
    '\t\tvelocity = input_vec * move_speed',
    '\t\tif absf(input_vec.x) > 0.05 and _sprite != null:',
    '\t\t\t_sprite.flip_h = input_vec.x < 0.0',
    '\telse:',
    '\t\tvar horiz := Input.get_axis("move_left", "move_right")',
    '\t\tvelocity.x = horiz * move_speed',
    '\t\tif absf(horiz) > 0.05 and _sprite != null:',
    '\t\t\t_sprite.flip_h = horiz < 0.0',
    '\t\tif is_on_floor():',
    '\t\t\t_coyote_timer = coyote_time_sec',
    '\t\telse:',
    '\t\t\t_coyote_timer = maxf(0.0, _coyote_timer - delta)',
    '\t\t\tvelocity.y += gravity_px * delta',
    '\t\tif Input.is_action_just_pressed("jump") and _coyote_timer > 0.0:',
    '\t\t\tvelocity.y = jump_velocity',
    '\t\t\t_coyote_timer = 0.0',
    '',
    '\tif Input.is_action_just_pressed("attack") and _attack_timer <= 0.0:',
    '\t\t_perform_attack()',
    '\telif Input.is_action_just_pressed("interact"):',
    '\t\t_try_interact()',
    '',
    '\tmove_and_slide()',
    '\t_update_animation()',
    '',
    'func _perform_attack() -> void:',
    '\t_attack_timer = attack_cooldown_sec',
    '\tif _fsm != null and _fsm.has_method("transition_to"):',
    '\t\t_fsm.call("transition_to", &"Attack")',
    '\tif _anim_player != null and _anim_player.has_animation("attack"):',
    '\t\t_anim_player.play("attack")',
    '',
    'func _update_animation() -> void:',
    '\tif _attack_timer > 0.0:',
    '\t\treturn',
    '\tvar moving := velocity.length() > 6.0',
    '\tif _fsm != null and _fsm.has_method("transition_to"):',
    '\t\t_fsm.call("transition_to", &"Move" if moving else &"Idle")',
    '\tif _anim_player != null and _anim_player.has_animation("idle") and not _anim_player.is_playing():',
    '\t\t_anim_player.play("idle")',
    '',
    'func _try_interact() -> void:',
    '\tvar npcs := get_tree().get_nodes_in_group(&"npc")',
    '\tvar best_npc: Node2D = null',
    '\tvar best_dist: float = 48.0',
    '\tfor raw_npc in npcs:',
    '\t\tif raw_npc is Node2D:',
    '\t\t\tvar d := global_position.distance_to((raw_npc as Node2D).global_position)',
    '\t\t\tif d <= best_dist:',
    '\t\t\t\tbest_dist = d',
    '\t\t\t\tbest_npc = raw_npc as Node2D',
    '\tif best_npc != null and best_npc.has_method("interact"):',
    '\t\tbest_npc.call("interact")',
    '',
    'func _on_hitbox_area_entered(area: Area2D) -> void:',
    '\tif area == null or area.get_parent() == self:',
    '\t\treturn',
    '\tvar target_parent := area.get_parent()',
    '\tif target_parent != null and target_parent.has_node("HealthComponent"):',
    '\t\tvar target_health := target_parent.get_node("HealthComponent")',
    '\t\tif target_health.has_method("take_damage"):',
    '\t\t\ttarget_health.call("take_damage", attack_damage)',
    '',
    'func _on_hurtbox_area_entered(area: Area2D) -> void:',
    '\tif _invuln_timer > 0.0 or area == null or area.get_parent() == self:',
    '\t\treturn',
    '\tvar attacker := area.get_parent()',
    '\tif attacker == null or attacker.is_in_group(&"player"):',
    '\t\treturn',
    '\tvar dmg := 10.0',
    '\tif attacker.get("attack_damage") != null:',
    '\t\tdmg = float(attacker.get("attack_damage"))',
    '\t_invuln_timer = 0.45',
    '\tif _health != null and _health.has_method("take_damage"):',
    '\t\t_health.call("take_damage", dmg)',
    '\t_trigger_hit_flash()',
    '',
    'func _trigger_hit_flash() -> void:',
    '\tif _sprite != null and _sprite.material is ShaderMaterial:',
    '\t\tvar sm := _sprite.material as ShaderMaterial',
    '\t\tsm.set_shader_parameter("hit_flash", 1.0)',
    '\t\tvar tw := create_tween()',
    '\t\ttw.tween_method(func(v: float): sm.set_shader_parameter("hit_flash", v), 1.0, 0.0, 0.16)',
    '',
  ].join('\n');

  const enemyGd = [
    'extends CharacterBody2D',
    'class_name NibgridEnemyAiController',
    '',
    '## Auto-generated by Nibgrid Milestone 56 (Playable F5 Enemy AI Controller)',
    '@export var move_speed: float = 88.0',
    '@export var chase_range_px: float = 160.0',
    '@export var attack_range_px: float = 28.0',
    '@export var attack_damage: float = 12.0',
    `@export var gravity_px: float = ${defaultGravity}`,
    `@export var top_down_movement: bool = ${isTopDown}`,
    '',
    '@onready var _sprite: Sprite2D = get_node_or_null("Sprite2D") as Sprite2D',
    '@onready var _anim_player: AnimationPlayer = get_node_or_null("AnimationPlayer") as AnimationPlayer',
    '@onready var _health: Node = get_node_or_null("HealthComponent")',
    '@onready var _hurtbox: Area2D = get_node_or_null("HurtboxComponent") as Area2D',
    '@onready var _fsm: Node = get_node_or_null("StateMachine")',
    '',
    'var _attack_cooldown: float = 0.0',
    '',
    'func _ready() -> void:',
    '\tadd_to_group(&"enemy")',
    '\tif _hurtbox != null and not _hurtbox.area_entered.is_connected(_on_hurtbox_area_entered):',
    '\t\t_hurtbox.area_entered.connect(_on_hurtbox_area_entered)',
    '\tif _health != null and _health.has_signal("died") and not _health.is_connected("died", _on_died):',
    '\t\t_health.connect("died", _on_died)',
    '',
    'func _physics_process(delta: float) -> void:',
    '\t_attack_cooldown = maxf(0.0, _attack_cooldown - delta)',
    '\tvar player := get_tree().get_first_node_in_group(&"player") as Node2D',
    '\tvar desired_dir := Vector2.ZERO',
    '\tvar next_state: StringName = &"Idle"',
    '',
    '\tif player != null:',
    '\t\tvar offset := player.global_position - global_position',
    '\t\tvar dist := offset.length()',
    '\t\tif dist <= attack_range_px and _attack_cooldown <= 0.0:',
    '\t\t\tnext_state = &"Attack"',
    '\t\t\t_attack_cooldown = 0.9',
    '\t\t\tif _anim_player != null and _anim_player.has_animation("attack"):',
    '\t\t\t\t_anim_player.play("attack")',
    '\t\telif dist <= chase_range_px:',
    '\t\t\tnext_state = &"Move"',
    '\t\t\tdesired_dir = offset.normalized() if dist > 0.001 else Vector2.ZERO',
    '',
    '\tif top_down_movement:',
    '\t\tvelocity = desired_dir * move_speed',
    '\telse:',
    '\t\tvelocity.x = signf(desired_dir.x) * move_speed if absf(desired_dir.x) > 0.1 else 0.0',
    '\t\tif not is_on_floor():',
    '\t\t\tvelocity.y += gravity_px * delta',
    '',
    '\tif absf(velocity.x) > 0.5 and _sprite != null:',
    '\t\t_sprite.flip_h = velocity.x < 0.0',
    '',
    '\tif _fsm != null and _fsm.has_method("transition_to"):',
    '\t\t_fsm.call("transition_to", next_state)',
    '',
    '\tmove_and_slide()',
    '',
    'func _on_hurtbox_area_entered(area: Area2D) -> void:',
    '\tif area == null or area.get_parent() == self:',
    '\t\treturn',
    '\tvar attacker := area.get_parent()',
    '\tif attacker == null or attacker.is_in_group(&"enemy"):',
    '\t\treturn',
    '\tvar dmg := 15.0',
    '\tif attacker.get("attack_damage") != null:',
    '\t\tdmg = float(attacker.get("attack_damage"))',
    '\tif _health != null and _health.has_method("take_damage"):',
    '\t\t_health.call("take_damage", dmg)',
    '\tif _sprite != null and _sprite.material is ShaderMaterial:',
    '\t\tvar sm := _sprite.material as ShaderMaterial',
    '\t\tsm.set_shader_parameter("hit_flash", 1.0)',
    '\t\tvar tw := create_tween()',
    '\t\ttw.tween_method(func(v: float): sm.set_shader_parameter("hit_flash", v), 1.0, 0.0, 0.14)',
    '',
    'func _on_died() -> void:',
    '\tqueue_free()',
    '',
  ].join('\n');

  const npcGd = [
    'extends CharacterBody2D',
    'class_name NibgridNpcController',
    '',
    '## Auto-generated by Nibgrid Milestone 56 (Interactive Dialogue NPC)',
    '@export var display_title: String = "Guide"',
    '@export var dialogue_entry_id: String = ""',
    '',
    'func _ready() -> void:',
    '\tadd_to_group(&"npc")',
    '',
    'func interact() -> void:',
    '\tvar runner := get_node_or_null("/root/DialogueRunner")',
    '\tif runner != null and runner.has_method("start_dialogue"):',
    '\t\trunner.call("start_dialogue", dialogue_entry_id)',
    '',
  ].join('\n');

  const saveManagerGd = [
    'extends Node',
    'class_name NibgridSaveManager',
    '',
    '## Auto-generated by Nibgrid Milestone 56 (Persistent user:// JSON Save/Load)',
    'const SAVE_PATH: String = "user://nibgrid_save.json"',
    '',
    'func has_save() -> bool:',
    '\treturn FileAccess.file_exists(SAVE_PATH)',
    '',
    'func save_state(state: Dictionary) -> bool:',
    '\tvar file := FileAccess.open(SAVE_PATH, FileAccess.WRITE)',
    '\tif file == null:',
    '\t\treturn false',
    '\tfile.store_string(JSON.stringify(state, "  "))',
    '\tfile.close()',
    '\treturn true',
    '',
    'func load_state() -> Dictionary:',
    '\tif not FileAccess.file_exists(SAVE_PATH):',
    '\t\treturn {}',
    '\tvar file := FileAccess.open(SAVE_PATH, FileAccess.READ)',
    '\tif file == null:',
    '\t\treturn {}',
    '\tvar parsed: Variant = JSON.parse_string(file.get_as_text())',
    '\tfile.close()',
    '\treturn parsed if parsed is Dictionary else {}',
    '',
    'func clear_save() -> void:',
    '\tif FileAccess.file_exists(SAVE_PATH):',
    '\t\tDirAccess.remove_absolute(ProjectSettings.globalize_path(SAVE_PATH))',
    '',
  ].join('\n');

  return [
    { relativePath: 'scripts/runtime/PlayerController.gd', content: playerGd },
    { relativePath: 'scripts/runtime/EnemyAiController.gd', content: enemyGd },
    { relativePath: 'scripts/runtime/NpcController.gd', content: npcGd },
    { relativePath: 'scripts/runtime/SaveManager.gd', content: saveManagerGd },
  ];
}
