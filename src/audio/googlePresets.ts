export function getGoogleAudioPreset(presetId: string): GoogleAudioPreset {
  return (
    GOOGLE_AUDIO_PRESETS.find((p) => p.id === presetId) ??
    GOOGLE_AUDIO_PRESETS.find((p) => p.id === 'sfx-sprite-impact')!
  );
}

export function compileAudioPresetPrompt(
  template: string,
  vars: {
    readonly subject?: string;
    readonly biome?: string;
    readonly mood?: string;
    readonly bpm?: number;
  },
): string {
  return template
    .replaceAll('{{subject}}', vars.subject?.trim() || '2D game character')
    .replaceAll('{{biome}}', vars.biome?.trim() || 'dark dungeon stone')
    .replaceAll('{{mood}}', vars.mood?.trim() || 'heroic retro indie')
    .replaceAll('{{bpm}}', String(vars.bpm ?? 128));
}
