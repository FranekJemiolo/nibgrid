import { z } from 'zod';
import {
  AudioCategorySchema,
  GoogleAudioRouteSchema,
  ProceduralSfxParamsSchema,
} from '../domain/schemas';
import type { GoogleAudioPreset, ProceduralSfxParams } from './types';

export const GoogleAudioPresetSchema = z.object({
  id: z.string().min(1),
  label: z.string().min(1),
  category: AudioCategorySchema,
  route: GoogleAudioRouteSchema,
  modelId: z.string().min(1),
  promptTemplate: z.string().min(1),
  attachActiveSpriteImage: z.boolean().optional(),
  ttsConfig: z
    .object({
      defaultVoice: z.string().min(1),
      styleDirection: z.string().min(1),
      sampleScript: z.string().min(1),
    })
    .optional(),
  realtimeConfig: z
    .object({
      bpm: z.number().int().min(40).max(240),
      density: z.number().min(0).max(1),
      brightness: z.number().min(0).max(1),
      weightedPrompts: z.array(
        z.object({
          text: z.string().min(1),
          weight: z.number().min(0).max(2),
        }),
      ),
    })
    .optional(),
  fallbackSynthParams: ProceduralSfxParamsSchema,
  postProcessDefaults: z.object({
    trimSilence: z.boolean(),
    silenceThresholdDb: z.number().min(-80).max(-12).optional(),
    targetLufs: z.number().min(-32).max(-6),
    seamlessLoop: z.boolean(),
    loopCrossfadeMs: z.number().min(10).max(1000),
    variationCount: z.union([z.literal(1), z.literal(4), z.literal(6)]),
    pitchShiftPercent: z.number().min(-50).max(50).optional(),
  }),
});

