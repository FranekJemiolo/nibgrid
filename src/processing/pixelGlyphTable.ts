function compile5x7Alpha(
  rows: readonly [string, string, string, string, string, string, string],
): Uint8Array {
  const alpha = new Uint8Array(5 * 7);
  for (let y = 0; y < 7; y++) {
    const row = rows[y] ?? '.....';
    for (let x = 0; x < 5; x++) {
      alpha[y * 5 + x] = row.charAt(x) === '#' ? 255 : 0;
    }
  }
  return alpha;
}

/**
 * Returns a pure-TS 5x7 monochrome glyph mask for any ASCII code point 32..126,
 * falling back cleanly to '?' for unsupported characters.
 */
export function getBuiltInGlyphMask(char: string): GlyphMask {
  const ch = char.length > 0 ? char.charAt(0) : ' ';
  const code = ch.charCodeAt(0);
  if (ch === ' ') {
    return {
      charCode: 32,
      char: ' ',
      width: 3,
      height: 7,
      alpha: new Uint8Array(3 * 7),
      xoffset: 0,
      yoffset: 0,
      xadvance: 4,
    };
  }

  const pattern = GLYPH_ROWS_5X7[ch] ?? GLYPH_ROWS_5X7['?']!;
  return {
    charCode: Number.isFinite(code) ? code : 63,
    char: ch,
    width: 5,
    height: 7,
    alpha: compile5x7Alpha(pattern),
    xoffset: 0,
    yoffset: 0,
    xadvance: 6,
  };
}

/**
 * Builds deduplicated built-in 5x7 `GlyphMask` entries in string order for a charset string or preset.
 */
export function buildBuiltInGlyphMasks(charset: string): GlyphMask[] {
  const seen = new Set<number>();
  const masks: GlyphMask[] = [];
  for (const ch of Array.from(charset)) {
    const code = ch.charCodeAt(0);
    if (seen.has(code)) continue;
    seen.add(code);
    masks.push(getBuiltInGlyphMask(ch));
  }
  return masks;
}
